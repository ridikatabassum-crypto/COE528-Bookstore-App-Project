     private void updateWelcomeLabel() {
    welcomeLabel.setText("Welcome " + customer.getUsername()
            + ". You have " + customer.getPoints()
            + " points. Your status is "
            + customer.getState().getStatusName());
}
     private void refreshTable() {
    tableModel.setRowCount(0);

    for (Book book : store.getBooks()) {
        tableModel.addRow(new Object[]{book.getName(), book.getPrice(), false});
    }
}

     private double getSelectedTotal() {
    double total = 0;

    for (int row = 0; row < tableModel.getRowCount(); row++) {
        Boolean isSelected = (Boolean) tableModel.getValueAt(row, 2);

        if (isSelected != null && isSelected) {
            double price = Double.parseDouble(tableModel.getValueAt(row, 1).toString());
            total = total+ price;
        }
    }

    return total;
}
     
