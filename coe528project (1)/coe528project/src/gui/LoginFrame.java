    private void loginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButtonActionPerformed
        // TODO add your handling code here:
        String username = usernameField.getText();//get what user typed in text field
        String password = new String(passwordField.getPassword());

      
        User user = store.login(username, password);//check login with Bookstore

        if (user == null) {
            JOptionPane.showMessageDialog(this, "ERROR username or password");
            return;
        }

        if (user instanceof Owner) {//owner class OBJECT
            new OwnerStartFrame(store).setVisible(true);//creates owner screen and passes store
            dispose();//close login
        } else if (user instanceof Customer) {//customer
            new CustomerStartFrame(store, (Customer) user).setVisible(true);//cast user into customer
            dispose();//close login
}
    }//GEN-LAST:event_loginButtonActionPerformed

